"""### 1. Importing Libraries

We'll use `tensorflow` for building and training the neural network, and `numpy` for numerical computations and array manipulations.
"""

import tensorflow as tf
import numpy as np

"""### 2. Defining the Dataset

We define the input `X` representing the AND gate inputs and the corresponding output labels `y`. The output is `1` only when both inputs are `1`, as per the truth table of the AND gate.
"""

X = np.array([[0, 0], [0, 1], [1, 0], [1, 1]], dtype=np.float32)
y = np.array([[0], [0], [0], [1]], dtype=np.float32)

"""### 3. Building the Neural Network Model

We construct a simple sequential model with one hidden layer and an output layer.

-   **`tf.keras.Sequential`**: Creates a linear stack of layers.
-   **First Layer (Hidden Layer)**:
    -   `Dense(4)`: A fully connected layer with 4 neurons.
    -   `input_dim=2`: Specifies that the input features are 2 (each input sample has two values).
    -   `activation='relu'`: Uses the Rectified Linear Unit (ReLU) activation function to introduce non-linearity.
-   **Second Layer (Output Layer)**:
    -   `Dense(1)`: Outputs a single value.
    -   `activation='sigmoid'`: Uses the sigmoid activation function, which outputs a value between 0 and 1, suitable for binary classification.
"""

model = tf.keras.Sequential([
    tf.keras.layers.Dense(4, input_dim=2, activation='relu'),  # Hidden layer
    tf.keras.layers.Dense(1, activation='sigmoid')              # Output layer
])

"""### 4. Compiling the Model

We compile the model by specifying the optimizer, loss function, and metrics.

-   **`optimizer='adam'`**: An efficient optimization algorithm.
-   **`loss='binary_crossentropy'`**: The loss function used for binary classification problems.
-   **`metrics=['accuracy']`**: Tracks the accuracy during training.
"""

model.compile(optimizer='adam', loss='binary_crossentropy', metrics=['accuracy'])

"""#### Predictions BEFORE Training

Let's see what the model predicts before any training. At this stage, the model's predictions are random as it has not yet learned any patterns.
"""

print("Predictions BEFORE training:")
untrained_predictions = model.predict(X)
for i, pred in enumerate(untrained_predictions):
    print(f"Input: {X[i]} => Predicted: {round(float(pred[0]), 4)} => Class: {int(pred[0] >= 0.5)}")

"""### 5. Training the Model

We train the model using our dataset for a specified number of epochs.

-   **`epochs=10`**: The model will iterate over the entire dataset 10 times.
-   **`verbose=2`**: Displays one line of output per epoch during training.
"""

model.fit(X, y, epochs=10, verbose=2)

"""### 6. Evaluating and Making Predictions

After training, we use the model to predict outputs for all input combinations. The sigmoid output is rounded and then classified (0 or 1) using a threshold of 0.5.
"""

predictions = model.predict(X)
print("\nPredictions AFTER training:")
for i, pred in enumerate(predictions):
    print(f"Input: {X[i]} => Predicted: {round(float(pred[0]), 4)} => Class: {int(pred[0] >= 0.5)}")

"""### Result

-   **Before training**, the model behaves randomly because it has no knowledge of the pattern.
-   **After training**, it learns to approximate the AND function, showing correct predictions for the given inputs.
"""